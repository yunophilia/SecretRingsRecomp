"""Writes runtime/install/releases_files.inc: path, size and SHA-1 of every installed file
(sys/, files/, ticket/tmd/cert/h3) of each supported release, for the launcher's
integrity checks. Files that are the same in several releases are listed once, with a
mask of the releases they belong to (Release::mask in runtime/install/releases.h).

  python tools/gen_file_manifest.py RSRE8P=<data dir> [RSRP8P=<data dir>] [RSRJ8P=<data dir>]

Each data dir is a known-good install (the installer's output and DolphinTool's
"extract -g" are byte-identical). Releases not given keep their entries from the current
file. Contains hashes only, no game data.
"""
import hashlib
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'runtime', 'install', 'releases_files.inc')
MASKS = {'RSRE8P': 1, 'RSRP8P': 2, 'RSRJ8P': 4}


def scan(data):
    rows = {}
    for d, _, fs in os.walk(data):
        for f in fs:
            p = os.path.join(d, f)
            rel = os.path.relpath(p, data).replace('\\', '/')
            if rel.startswith('disc/'):
                continue   # written by the installer only, not part of a DolphinTool extraction
            h = hashlib.sha1()
            with open(p, 'rb') as fp:
                for chunk in iter(lambda: fp.read(1 << 20), b''):
                    h.update(chunk)
            rows[rel] = (os.path.getsize(p), h.hexdigest())
    return rows


def main():
    entries = {}   # (path, size, sha1) -> mask
    given = 0
    for arg in sys.argv[1:]:
        gid, data = arg.split('=', 1)
        with open(os.path.join(data, 'sys', 'boot.bin'), 'rb') as fp:
            if fp.read(6).decode() != gid:
                sys.exit(f'{data} is not {gid}')
        given |= MASKS[gid]
        for rel, (size, sha) in scan(data).items():
            entries[(rel, size, sha)] = entries.get((rel, size, sha), 0) | MASKS[gid]
    if os.path.exists(OUT):
        pat = re.compile(r'\{ "([^"]+)", (\d+)ull, "([0-9a-f]+)", (\d+) \}')
        for m in pat.finditer(open(OUT).read()):
            keep = int(m.group(4)) & ~given
            if keep:
                k = (m.group(1), int(m.group(2)), m.group(3))
                entries[k] = entries.get(k, 0) | keep
    rows = sorted(entries.items())
    with open(OUT, 'w', newline='\n') as fp:
        fp.write('// Generated by tools/gen_file_manifest.py: installed files of each release\n'
                 '// (path, size, SHA-1, mask of the releases: 1 RSRE8P, 2 RSRP8P, 4 RSRJ8P)\n')
        for (rel, size, sha), mask in rows:
            fp.write(f'{{ "{rel}", {size}ull, "{sha}", {mask} }},\n')
    print(len(rows), 'entries ->', OUT)


if __name__ == '__main__':
    main()
