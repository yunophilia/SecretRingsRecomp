"""Plays Adventure mode from a new file to the end, one mission per run, and records what
happened (docs/tas.md, "Story playthrough").

  python tools/story_run.py [--fps 30|60] [--name story60] [--max-runs N] [--fresh]

Missions are made easier in a test copy of the game data (out/storydata: hard links to
game/extracted/DATA except files/actstgmission.txt; see convert_missions), so a script
can clear them by running forward with jumps and homing attacks, while the game itself decides what each clear unlocks
and runs every story scene, results screen, unlock dialog and save in between. Each run
starts the game on the save the previous run left (out/tasnand/<name>), picks a mission
in the world/mission wheels by position and plays it until the goal file is read, then
goes through the results until the world menu is loaded again (after the save is
written). The driver reads game_0.sav after each run to see whether anything changed,
and tries the next mission position, or another world, when nothing did.

State (resumable): out/story/<name>/state.json; per-run logs and shots: out/tas/.
"""
import argparse
import hashlib
import json
import os
import re
import shutil
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'out')
DATA = os.path.join(ROOT, 'game', 'extracted', 'DATA')
STORYDATA = os.path.join(OUT, 'storydata', 'DATA')
WORLDS = ['Lost Prologue', 'Sand Oasis', 'Dinosaur Jungle', 'Evil Foundry', 'Levitated Ruin',
          'Pirate Storm', 'Skeleton Dome', 'Night Palace']
SAVE_REL = os.path.join('title', '00010000', '52535245', 'data', 'game_0.sav')


# mission_type bits (actstgmission.txt comments): counts kept with a target of 1, time
# attacks get 999 s, and conditions that fail a run (no deaths/damage/rings/pearls/kills,
# don't break pots) and the race against Uhu are dropped, leaving "reach the goal"
COUNT_TYPES = 0x1 | 0x2 | 0x4 | 0x10 | 0x40 | 0x8000   # rings, pots/eggs, enemies, ring chains, bones, actions
TIME_ATTACK = 0x80000
DROPPED = 0x8 | 0x10000 | 0x20000 | 0x40000 | 0x100000 | 0x200000 | 0x400000


def convert_missions(text):
    out, block = [], None

    def flush(lines, mtype):
        mtype &= ~DROPPED
        for l in lines:
            s = l.strip()
            ind = l[:len(l) - len(l.lstrip())]
            cr = '\r' if l.endswith('\r') else ''
            if re.match(r'mission_type\b', s):
                if mtype:
                    out.append(f'{ind}mission_type {mtype:#x}{cr}')
            elif re.match(r'mission_targets\b', s):
                if mtype & TIME_ATTACK:
                    out.append(f'{ind}mission_targets 999{cr}')
                elif mtype & COUNT_TYPES:
                    out.append(f'{ind}mission_targets 1{cr}')
            else:
                out.append(l)

    for line in text.split('\n'):
        s = line.strip()
        if re.match(r'mission\s+\d+\s*\{', s):
            block = [[line], 0]
            continue
        if block is not None:
            block[0].append(line)
            m = re.match(r'mission_type\s+(0x[0-9a-fA-F]+|\d+)', s)
            if m:
                block[1] = int(m.group(1), 0)
            if s.startswith('}'):
                flush(*block)
                block = None
            continue
        out.append(line)
    return '\n'.join(out)


def make_storydata():
    """Hard-linked copy of the game data with easier missions (convert_missions)."""
    src = os.path.join(DATA, 'files', 'actstgmission.txt')
    dst = os.path.join(STORYDATA, 'files', 'actstgmission.txt')
    if not os.path.exists(os.path.join(STORYDATA, 'sys')):
        for dirpath, _, files in os.walk(DATA):
            rel = os.path.relpath(dirpath, DATA)
            os.makedirs(os.path.join(STORYDATA, rel), exist_ok=True)
            for f in files:
                d = os.path.join(STORYDATA, rel, f)
                if not os.path.exists(d):
                    os.link(os.path.join(dirpath, f), d)
    text = convert_missions(open(src, 'rb').read().decode('cp932'))
    if os.path.exists(dst):
        os.remove(dst)   # a hard link to the original: never write through it
    open(dst, 'wb').write(text.encode('cp932'))


def read_save(nand):
    p = os.path.join(nand, SAVE_REL)
    return open(p, 'rb').read() if os.path.exists(p) else None


def summary(d):
    if d is None:
        return {'worlds': 0, 'unlocked': 0, 'cleared': 0}
    recs = [d[o:o + 16] for o in range(0x10, 0x700, 16)]
    return {'worlds': sum(1 for w in range(0x09, 0x10) if d[w]),
            'unlocked': sum(1 for r in recs if r[0]),
            'cleared': sum(1 for r in recs if r[4])}


def menu_script(world, pos):
    s = ['# generated by tools/story_run.py', 'wait 8', 'repeat 9', 'tap A', 'wait 1.4', 'end',
         'shot world_before']
    s += ['tap DOWN', 'wait 1.5'] * world
    s += ['shot world', 'tap A', 'wait 2.5']
    s += ['tap DOWN', 'wait 0.8'] * pos
    s += ['shot list', 'tap A', 'wait 2.5', 'shot ready', 'tap A', 'wait 1']
    return s


def first_script():
    return ['# generated by tools/story_run.py: new file, Lost Prologue Paragraph 01',
            'include ' + os.path.join(ROOT, 'tools', 'tas', 'boot_stage1.tas').replace('\\', '/')]


TAIL = ['filemark', 'log mission start',
        # a little backwards first (some missions are behind the start), then jumps +
        # homing attacks in the air, braking, slower presses (longer ones charge the jump)
        'set LY=-1', 'until file goal_2d mash A period 1 timeout 15 soft', 'set',
        # (steering left and right keeps Sonic off walls)
        'until file goal_2d mash A+LX=-1,X,A+LX=1,X period 0.6 timeout 300 soft',
        'shot play', 'until file goal_2d mash B period 8 timeout 100 soft',   # brake 4 s, run 4 s
        'shot play', 'until file goal_2d mash A+LX=-1,X,A+LX=1,X period 1 timeout 100 soft',
        'shot play', 'until file goal_2d mash A+LX=-1,A+LX=1 period 1.6 timeout 150',
        'log goal', 'shot goal', 'filemark',
        'until file adv_main_menu mash A+B timeout 480',
        'log menu', 'wait 3', 'shot menu', 'wait 1', 'quit']


def run(script_lines, tag, save, fps, seconds=1500):
    sdir = os.path.join(OUT, 'story', 'scripts')
    os.makedirs(sdir, exist_ok=True)
    sp = os.path.join(sdir, tag + '.tas')
    open(sp, 'w', newline='\n').write('\n'.join(script_lines) + '\n')
    cmd = ['powershell', '-ExecutionPolicy', 'Bypass', '-File', os.path.join(ROOT, 'tools', 'tas_run.ps1'),
           '-Script', sp, '-Save', save, '-Tag', tag, '-Seconds', str(seconds),
           '-ExtraArgs', f'--data "{STORYDATA}"']
    if fps == 60:
        cmd.append('-Fps60')
    r = subprocess.run(cmd, capture_output=True, text=True)
    return r.stdout.strip()


def log_stats(tag):
    p = os.path.join(OUT, 'tas', tag + '.log')
    if not os.path.exists(p):
        return {}
    fps, errors, events = [], [], []
    for line in open(p, encoding='utf8', errors='replace'):
        m = re.search(r'status: ([\d.]+) fps', line)
        if m:
            fps.append(float(m.group(1)))
        if '[E]' in line or 'TAS: FAIL' in line:
            errors.append(line.strip())
        m = re.search(r'TAS: (mission start|goal|menu)$', line.strip())
        if m:
            events.append(m.group(1))
        m = re.search(r'files/(movie/\S+|inter_event\S*|stg\d+\.one)', line)
        if m and m.group(1) not in events:
            events.append(m.group(1))
    fps = fps[1:]   # the first sample covers the boot
    return {'fps_min': min(fps) if fps else None, 'fps_med': sorted(fps)[len(fps) // 2] if fps else None,
            'errors': errors[:5], 'events': events}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--fps', type=int, default=60)
    ap.add_argument('--name', default=None)
    ap.add_argument('--max-runs', type=int, default=400)
    ap.add_argument('--fresh', action='store_true')
    a = ap.parse_args()
    name = a.name or f'story{a.fps}'
    sdir = os.path.join(OUT, 'story', name)
    nand = os.path.join(OUT, 'tasnand', name)
    state_p = os.path.join(sdir, 'state.json')
    if a.fresh and os.path.exists(sdir):
        shutil.rmtree(sdir)
    os.makedirs(sdir, exist_ok=True)
    make_storydata()
    st = json.load(open(state_p)) if os.path.exists(state_p) else \
        {'runs': [], 'next': [0] * len(WORLDS), 'fails': {}, 'blocked': {}}
    if not st['runs']:
        if os.path.exists(nand):
            shutil.rmtree(nand)
        os.makedirs(nand)

    def save_state():
        json.dump(st, open(state_p, 'w'), indent=1)

    while len(st['runs']) < a.max_runs:
        before = read_save(nand)
        sig = hashlib.sha1(before).hexdigest() if before else 'none'
        s = summary(before)
        if before is None:
            w, pos, lines = 0, 0, first_script()
        else:
            cand = [w for w in range(len(WORLDS))
                    if (w == 0 or before[0x08 + w]) and st['blocked'].get(str(w)) != sig]
            if not cand:
                print('nothing left to try', flush=True)
                break
            last = st.get('last')
            w = last if last in cand else cand[0]   # stay in a world while it gives clears
            pos = st['next'][w]
            lines = menu_script(w, pos)
        tag = f'{name}_{len(st["runs"]):03d}'
        res = run(lines + TAIL, tag, name, a.fps)
        after = read_save(os.path.join(OUT, 'tasnand', 'run_' + tag))
        changed = after is not None and after != before
        if changed:
            shutil.rmtree(nand)
            shutil.copytree(os.path.join(OUT, 'tasnand', 'run_' + tag), nand)
        s2 = summary(after if changed else before)
        cleared_more = s2['cleared'] > s['cleared']
        key = f'{w}:{pos}'
        if cleared_more:
            st['next'][w] = pos + 1
            st['blocked'] = {}
            st['last'] = w
        elif changed:
            st['blocked'] = {}   # something else changed (a story flag, a better time): retry
            st['fails'][key] = st['fails'].get(key, 0) + 1
        else:
            st['fails'][key] = st['fails'].get(key, 0) + 1
        if not cleared_more and (not changed or st['fails'][key] >= 2):
            st['last'] = None
            st['blocked'][str(w)] = hashlib.sha1(after if changed else before).hexdigest() if (after or before) else 'none'
        entry = {'tag': tag, 'world': WORLDS[w], 'pos': pos, 'result': res.splitlines()[0] if res else '',
                 'before': s, 'after': s2, 'changed': changed, **log_stats(tag)}
        st['runs'].append(entry)
        save_state()
        print(json.dumps({k: entry[k] for k in ('tag', 'world', 'pos', 'result', 'after', 'changed', 'fps_min', 'fps_med')}),
              flush=True)
    save_state()


if __name__ == '__main__':
    main()
